// Anti-cheat: the minimal repro becomes a Kane `_test.md` whose sha256 is recorded before any
// agent sees the code. Judges always read the trusted copy and re-check the hash; an agent that
// touches its copy (or any protected path) is disqualified.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { STRICT } from './objective.ts';
import { incidentDir, writeJson } from './store.ts';
import type { Incident, Repro } from './types.ts';

export type Lock = { file: string; repoPath: string; sha256: string; lockedAt: string; objective: string };

export const sha256 = (s: string | Buffer) => createHash('sha256').update(s).digest('hex');

export function testmdFor(inc: Incident, repro: Repro): string {
  const steps = repro.steps.map((s) => s.text.replace(/\.$/, '')).join('. ');
  return `---
mode: testing
max_steps: 30
tags: [regression, proof]
---

# ${inc.title ?? inc.id}

<!-- Generated by Proof from incident ${inc.id}. Hash-locked: do not edit. -->

## Reproduce ${inc.id}
${STRICT} ${steps}. ${repro.expectation}
`;
}

export function lockRepro(inc: Incident, repro: Repro, regressionsDir: string): Lock {
  const name = `${inc.id}_test.md`;
  const content = testmdFor(inc, repro);
  mkdirSync(incidentDir(inc.id), { recursive: true });
  const file = join(incidentDir(inc.id), name);
  writeFileSync(file, content);
  const objective = `${STRICT}\n${repro.steps.map((s, i) => `${i + 1}. ${s.text}`).join('\n')}\n${repro.steps.length + 1}. ${repro.expectation}`;
  const lock: Lock = {
    file,
    repoPath: join(regressionsDir, name),
    sha256: sha256(content),
    lockedAt: new Date().toISOString(),
    objective,
  };
  writeJson(inc.id, 'lock.json', lock);
  return lock;
}

/**
 * Throws if the trusted copy changed since locking. Returns the objective parsed from the hashed
 * file itself, so nothing outside the hash can alter what Kane is asked to check.
 */
export function assertLocked(lock: Lock): string {
  const content = readFileSync(lock.file, 'utf8');
  const now = sha256(content);
  if (now !== lock.sha256) throw new Error(`LOCK BROKEN: ${lock.file} sha256 ${now} != ${lock.sha256}`);
  const body = content.split(/^## .*$/m)[1]?.trim();
  if (!body) throw new Error(`LOCK BROKEN: ${lock.file} has no step body`);
  return body;
}

/** Did a worktree's copy of the locked test drift from the trusted one? */
export function tamperedCopy(worktree: string, lock: Lock): boolean {
  const f = join(worktree, lock.repoPath);
  return existsSync(f) && sha256(readFileSync(f)) !== lock.sha256;
}
